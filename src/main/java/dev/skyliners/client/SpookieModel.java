package dev.skyliners.client;

import dev.skyliners.Skyliners;
import dev.skyliners.entity.Spookie;
import net.minecraft.client.model.HierarchicalModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.util.Mth;

/**
 * The Spookie's model (see {@link Spookie}), built at its full size, two and a half blocks tall: a broad, slightly
 * stooped body under a cream mane over its shoulders, a big head with a heavy brow, a wide flat snout, two small lower
 * tusks and brass goggles pushed up on its brow, long tufted ears, arms hanging to its knees, sturdy legs and big feet,
 * a satchel at one hip and a wrench in its harness at the other. It strolls with its arms swinging against its legs;
 * greeting someone it throws both arms up over its head; and its ears show how it feels: pricked up and forward when
 * happy, laid flat back when alarmed, so anyone who cannot read sees it.
 *
 * <p>Its texture (generated by {@code tools/generate_textures.mjs}, which keeps the same places) has each box's faces
 * at its own corner, as {@link #createBodyLayer} lists them.
 */
public class SpookieModel extends HierarchicalModel<Spookie> {
    public static final ModelLayerLocation LAYER = new ModelLayerLocation(ResourceLocation.fromNamespaceAndPath(Skyliners.MOD_ID, "spookie"), "main");
    /** The texture's size, in pixels. */
    private static final int TEXTURE_WIDTH = 128;
    private static final int TEXTURE_HEIGHT = 64;
    /**
     * Where its hips are, over the ground, in the model's pixels (the ground at 24), and how far its body stoops, in
     * radians.
     */
    private static final float HIPS = 8;
    private static final float STOOP = 0.14F;
    /** How far its legs and its arms swing walking, in radians, and how fast with how far it walks. */
    private static final float LEG_SWING = 0.7F;
    private static final float ARM_SWING = 0.45F;
    private static final float STRIDE_RATE = 0.5F;
    /** How far its arms go up over its head greeting, and out to the sides, in radians. */
    private static final float ARMS_UP = 2.7F;
    private static final float ARMS_OUT = 0.35F;
    /**
     * Its ears: how far out from upright they lean as they are, pricked up when happy and laid back when alarmed, and
     * how far forward or back, in radians.
     */
    private static final float EARS_OUT = 0.55F;
    private static final float EARS_PRICKED_OUT = 0.2F;
    private static final float EARS_PRICKED_FORWARD = -0.35F;
    private static final float EARS_BACK_OUT = 1.0F;
    private static final float EARS_BACK = 1.2F;
    /** How far its arms sway idly, in radians, and how fast, in radians a tick. */
    private static final float IDLE_SWAY = 0.04F;
    private static final float IDLE_RATE = 0.06F;

    private final ModelPart root;
    private final ModelPart body;
    private final ModelPart head;
    private final ModelPart leftEar;
    private final ModelPart rightEar;
    private final ModelPart leftArm;
    private final ModelPart rightArm;
    private final ModelPart leftLeg;
    private final ModelPart rightLeg;
    /** How far its arms are up greeting this frame, from 0 to 1. */
    private float greeting;

    public SpookieModel(ModelPart root) {
        this.root = root;
        body = root.getChild("body");
        head = body.getChild("head");
        leftEar = head.getChild("left_ear");
        rightEar = head.getChild("right_ear");
        leftArm = body.getChild("left_arm");
        rightArm = body.getChild("right_arm");
        leftLeg = root.getChild("left_leg");
        rightLeg = root.getChild("right_leg");
    }

    /**
     * Its boxes, each with its faces at its own corner of the texture: the body at 0,0 and the mane over it at 44,0;
     * the head at 0,25, its snout at 36,25, brow at 36,31, tusks at 56,25, goggle strap at 56,31 and lenses at 78,34,
     * ears at 78,25, their tips at 86,25 and tufts at 90,25; the arms at 96,0; the legs at 88,31 and feet at 0,44; the
     * satchel at 28,44 and the wrench at 42,44.
     */
    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = new MeshDefinition();
        PartDefinition root = mesh.getRoot();
        PartDefinition body = root.addOrReplaceChild("body", CubeListBuilder.create()
            .texOffs(0, 0).addBox(-7, -15, -4, 14, 15, 8)
            .texOffs(44, 0).addBox(-8, -16, -5, 16, 8, 10)
            .texOffs(28, 44).addBox(7, -4, -2, 3, 6, 4)
            .texOffs(42, 44).addBox(-9, -7, 1, 2, 9, 1), PartPose.offsetAndRotation(0, HIPS, 0, STOOP, 0, 0));
        PartDefinition head = body.addOrReplaceChild("head", CubeListBuilder.create()
            .texOffs(0, 25).addBox(-4.5F, -10, -5, 9, 10, 9)
            .texOffs(36, 25).addBox(-2.5F, -5, -7, 5, 4, 2)
            .texOffs(36, 31).addBox(-4.5F, -8, -6, 9, 2, 1)
            .texOffs(56, 25).addBox(-2, -2, -6.5F, 1, 2, 1)
            .texOffs(56, 25).addBox(1, -2, -6.5F, 1, 2, 1)
            .texOffs(56, 31).addBox(-5, -10.5F, -5.5F, 10, 2, 1)
            .texOffs(78, 34).addBox(-3.5F, -11, -6.5F, 2, 2, 1)
            .texOffs(78, 34).addBox(1.5F, -11, -6.5F, 2, 2, 1), PartPose.offset(0, -16, -1));
        head.addOrReplaceChild("left_ear", ear(false), PartPose.offset(4, -9, 0));
        head.addOrReplaceChild("right_ear", ear(true), PartPose.offset(-4, -9, 0));
        body.addOrReplaceChild("left_arm", CubeListBuilder.create().texOffs(96, 0).addBox(-1, -1, -2.5F, 4, 24, 5), PartPose.offset(8, -13, 0));
        body.addOrReplaceChild("right_arm", CubeListBuilder.create().texOffs(96, 0).mirror().addBox(-3, -1, -2.5F, 4, 24, 5),
            PartPose.offset(-8, -13, 0));
        root.addOrReplaceChild("left_leg", leg(false), PartPose.offset(3.5F, HIPS, 0));
        root.addOrReplaceChild("right_leg", leg(true), PartPose.offset(-3.5F, HIPS, 0));
        return LayerDefinition.create(mesh, TEXTURE_WIDTH, TEXTURE_HEIGHT);
    }

    /** A long pointed ear standing up from its root, broad at its base as a lynx's, its tip narrow and tufted. */
    private static CubeListBuilder ear(boolean mirrored) {
        return CubeListBuilder.create().mirror(mirrored).texOffs(78, 25).addBox(-1.5F, -5, -0.5F, 3, 5, 1)
            .texOffs(86, 25).addBox(-0.5F, -7, -0.5F, 1, 2, 1).texOffs(90, 25).addBox(-0.5F, -9, -0.5F, 1, 2, 1);
    }

    /** A leg from its hip down, and its big foot. */
    private static CubeListBuilder leg(boolean mirrored) {
        return CubeListBuilder.create().mirror(mirrored).texOffs(88, 31).addBox(-3, 0, -3, 6, 16, 6).texOffs(0, 44).addBox(-3, 14, -5, 6, 2, 8);
    }

    @Override
    public ModelPart root() {
        return root;
    }

    @Override
    public void prepareMobModel(Spookie spookie, float limbSwing, float limbSwingAmount, float partialTick) {
        greeting = spookie.greeting(partialTick);
    }

    @Override
    public void setupAnim(Spookie spookie, float limbSwing, float limbSwingAmount, float ageInTicks, float netHeadYaw, float headPitch) {
        root.getAllParts().forEach(ModelPart::resetPose);
        head.yRot = netHeadYaw * Mth.DEG_TO_RAD;
        head.xRot = headPitch * Mth.DEG_TO_RAD - STOOP;
        float stride = Mth.cos(limbSwing * STRIDE_RATE) * limbSwingAmount;
        leftLeg.xRot = LEG_SWING * stride;
        rightLeg.xRot = -LEG_SWING * stride;
        float sway = IDLE_SWAY * Mth.sin(ageInTicks * IDLE_RATE);
        leftArm.xRot = -ARM_SWING * stride - STOOP + sway - ARMS_UP * greeting;
        rightArm.xRot = ARM_SWING * stride - STOOP - sway - ARMS_UP * greeting;
        leftArm.zRot = -ARMS_OUT * greeting;
        rightArm.zRot = ARMS_OUT * greeting;
        ears(spookie.mood());
    }

    /** Its ears as it feels: as they are, pricked up and forward, or laid flat back. */
    private void ears(Spookie.Mood mood) {
        float out = switch (mood) {
            case HAPPY -> EARS_PRICKED_OUT;
            case ALARMED -> EARS_BACK_OUT;
            case CALM -> EARS_OUT;
        };
        float back = switch (mood) {
            case HAPPY -> EARS_PRICKED_FORWARD;
            case ALARMED -> EARS_BACK;
            case CALM -> 0;
        };
        leftEar.zRot = out;
        rightEar.zRot = -out;
        leftEar.xRot = back;
        rightEar.xRot = back;
    }
}
