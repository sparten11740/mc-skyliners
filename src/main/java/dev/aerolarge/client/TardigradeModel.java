package dev.aerolarge.client;

import com.mojang.blaze3d.vertex.PoseStack;
import com.mojang.blaze3d.vertex.VertexConsumer;
import dev.aerolarge.Aerolarge;
import dev.aerolarge.entity.Tardigrade;
import net.minecraft.client.model.HierarchicalModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.client.renderer.LightTexture;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.util.FastColor;
import net.minecraft.util.Mth;

/**
 * The tardigrade's model (see {@link Tardigrade}), built as vanilla's creatures are, at half its size (see
 * {@link TardigradeRenderer}): a plump body of four segments, each rounded from three boxes and parted from the next by
 * a fold, a round head with two dark eye spots and a small round mouth at the tip of its snout, and eight stubby legs
 * with pale claws, the last pair pointing back. It lumbers on its legs in a wave from back to front, its segments
 * swaying; it munches with its head bobbing and its mouth working; touched, it wriggles. Asleep it settles low on
 * its tucked-up legs, its head resting down and still, its eyes shut under their lids and its body rising and falling
 * slowly as it breathes. Curling up into its tun it draws its legs and head in, its segments close up into a short
 * wrinkled barrel resting on the floor, and it dries a shade darker. Charging up to jump through the spore drive it
 * glows a flickering spore blue, brighter the nearer it is to going.
 *
 * <p>Its texture (generated by {@code tools/generate_textures.mjs}) is skin all over but for a few patches: the folds',
 * the claws', the mouth's, the eyes' and the snout's, where the boxes that are those take their faces from.
 */
public class TardigradeModel extends HierarchicalModel<Tardigrade> {
    public static final ModelLayerLocation LAYER = new ModelLayerLocation(ResourceLocation.fromNamespaceAndPath(Aerolarge.MOD_ID, "tardigrade"), "main");
    /** The texture's size, in pixels, and where its patches are. */
    private static final int TEXTURE_WIDTH = 128;
    private static final int TEXTURE_HEIGHT = 128;
    private static final int FOLD_V = 80;
    private static final int CLAW_V = 112;
    private static final int LIP_U = 32;
    private static final int EYE_U = 48;
    private static final int SNOUT_U = 64;
    /**
     * Where each of the skin's boxes takes its faces from, about the skin's part of the texture, so they look apart.
     */
    private static final int[][] SKIN = {{0, 0}, {60, 0}, {0, 30}, {60, 30}, {0, 52}, {60, 52}};
    /** The four segments, head to tail: their middles' height and place along the body, in the model's pixels. */
    private static final float[][] SEGMENTS = {{9, -8}, {8, 2.5F}, {8.5F, 12.5F}, {10, 20.5F}};
    /**
     * Each segment's three boxes, rounding it: the main one, a wider one low down and a taller one, by width, height
     * and length, and their tops and lengths about the segment's middle.
     */
    private static final float[][][] ROUNDING = {
        {{16, 17, 10, -9}, {20, 11, 8, -4}, {11, 17, 8, -11}},
        {{18, 19, 10, -10}, {22, 12, 8, -4}, {12, 20, 8, -13}},
        {{17, 18, 9, -9.5F}, {21, 11, 8, -3.5F}, {11, 18, 8, -12}},
        {{14, 15, 7, -8}, {18, 9, 6, -3}, {9, 15, 6, -10}}};
    /** The legs: their hips' place across and along the body, in pixels, how far they lean back, in radians. */
    private static final float[][] LEGS = {{8.5F, -8, 0}, {9, 2.5F, 0}, {8.5F, 12.5F, 0}, {6.5F, 20, 0.6F}};
    private static final float HIPS = 14;
    /** How far a leg swings walking, in radians, and how fast its stride goes with how far it walks. */
    private static final float STRIDE = 0.45F;
    private static final float STRIDE_RATE = 0.9F;
    /** How far the segments sway walking and wriggling, in radians. */
    private static final float SWAY = 0.05F;
    private static final float WRIGGLE = 0.14F;
    /** How far the head bobs munching, in radians, and how much its mouth opens. */
    private static final float BOB = 0.12F;
    private static final float CHEW = 0.35F;
    /**
     * How the body closes up curling into its tun: each segment's move along it and down, in pixels; its fattening and
     * flattening.
     */
    private static final float[] TUN_ALONG = {5, 1.5F, -2, -6};
    private static final float TUN_DROP = 7.5F;
    private static final float TUN_FATTER = 0.08F;
    private static final float TUN_FLATTER = 0.15F;
    private static final float TUN_HEAD_IN = 9;
    /**
     * How it lies asleep: how far its body sinks, in pixels, and how much its legs fold under it, a share of their ten
     * pixels' length, as much as the body sinks, so its feet stay on the floor; how far its head drops further and tips
     * down, in pixels and radians, its chin coming to rest on the moss half a pixel over the floor; and how deep and
     * slow its breath is, a share of its height and radians a tick.
     */
    private static final float SLEEP_DROP = 3.5F;
    private static final float SLEEP_LEG_FOLD = SLEEP_DROP / 10;
    private static final float SLEEP_HEAD_DROP = 1;
    private static final float SLEEP_HEAD_TIP = 0.25F;
    private static final float SLEEP_BREATH = 0.035F;
    private static final float SLEEP_BREATH_RATE = 0.06F;
    /** The shade it dries to curled up, multiplied over its colours; the spore blue it glows charging up to jump. */
    private static final int TUN_SHADE = 0xFFD6C2A8;
    private static final int SPORE_GLOW = 0xFFB0ECFF;
    /**
     * How far through its charge it glows at full brightness, whatever the light round it, and how much of its glow
     * flickers away from frame to frame at most.
     */
    private static final float GLOWS_FROM = 0.3F;
    private static final float GLOW_FLICKER = 0.3F;

    private final ModelPart root;
    private final ModelPart head;
    private final ModelPart lip;
    private final ModelPart lids;
    private final ModelPart[] segments = new ModelPart[SEGMENTS.length];
    private final ModelPart[] legs = new ModelPart[LEGS.length * 2];
    /**
     * How far it has curled, settled down asleep, charged up to jump, munches and wriggles this frame, set before each
     * frame is drawn.
     */
    private float curl;
    private float sleep;
    private float charge;
    private float munch;
    private float wriggle;

    public TardigradeModel(ModelPart root) {
        this.root = root;
        this.head = root.getChild("head");
        this.lip = head.getChild("lip");
        this.lids = head.getChild("lids");
        for (int i = 0; i < segments.length; i++) {
            segments[i] = root.getChild("segment" + i);
        }
        for (int i = 0; i < legs.length; i++) {
            legs[i] = root.getChild("leg" + i);
        }
    }

    /** The model's boxes and their texture patches. */
    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = new MeshDefinition();
        PartDefinition root = mesh.getRoot();
        for (int i = 0; i < SEGMENTS.length; i++) {
            root.addOrReplaceChild("segment" + i, segment(i), PartPose.offset(0, SEGMENTS[i][0], SEGMENTS[i][1]));
        }
        head(root);
        for (int i = 0; i < LEGS.length * 2; i++) {
            float[] leg = LEGS[i / 2];
            float side = i % 2 == 0 ? 1 : -1;
            root.addOrReplaceChild("leg" + i, leg(leg[2] > 0), PartPose.offsetAndRotation(side * leg[0], HIPS, leg[1], leg[2], 0, 0));
        }
        return LayerDefinition.create(mesh, TEXTURE_WIDTH, TEXTURE_HEIGHT);
    }

    /** A segment's three rounding boxes, and the fold before it, parting it from the one ahead. */
    private static CubeListBuilder segment(int index) {
        CubeListBuilder boxes = CubeListBuilder.create();
        for (int box = 0; box < 3; box++) {
            float[] size = ROUNDING[index][box];
            int[] patch = SKIN[(index + box) % SKIN.length];
            boxes.texOffs(patch[0], patch[1]).addBox(-size[0] / 2, size[3], -size[2] / 2, size[0], size[1], size[2]);
        }
        if (index > 0) {
            float[] main = ROUNDING[index][0];
            float length = main[2];
            boxes.texOffs(index * 32 - 32, FOLD_V).addBox(-main[0] / 2 + 1.5F, main[3] + 1.5F, -length / 2 - 1, main[0] - 3, main[1] - 2, 1.5F);
        }
        if (index == SEGMENTS.length - 1) {
            boxes.texOffs(96, FOLD_V).addBox(-5, -5, ROUNDING[index][0][2] / 2, 10, 10, 0.5F);
        }
        return boxes;
    }

    /** The head on the front segment: rounded from three boxes, its snout, its eye spots and its mouth. */
    private static void head(PartDefinition root) {
        CubeListBuilder boxes = CubeListBuilder.create()
            .texOffs(SKIN[1][0], SKIN[1][1]).addBox(-7, -6, -9, 14, 12, 9)
            .texOffs(SKIN[3][0], SKIN[3][1]).addBox(-8, -3, -8, 16, 8, 7)
            .texOffs(SKIN[5][0], SKIN[5][1]).addBox(-5, -8, -8, 10, 13, 7)
            .texOffs(SNOUT_U, CLAW_V).addBox(-3.5F, -1.5F, -12, 7, 6, 3)
            .texOffs(EYE_U, CLAW_V).addBox(2.5F, -5, -9.5F, 1, 1, 1)
            .texOffs(EYE_U, CLAW_V).addBox(-3.5F, -5, -9.5F, 1, 1, 1);
        PartDefinition head = root.addOrReplaceChild("head", boxes, PartPose.offset(0, 11, -12.5F));
        head.addOrReplaceChild("lip", CubeListBuilder.create().texOffs(LIP_U, CLAW_V).addBox(-2.5F, -2, -0.5F, 5, 4, 1), PartPose.offset(0, 1.5F, -12));
        // Its lids, in its skin, shut over its eye spots while it sleeps.
        head.addOrReplaceChild("lids", CubeListBuilder.create()
            .texOffs(SKIN[1][0], SKIN[1][1]).addBox(2.3F, -5.2F, -9.7F, 1.4F, 1.4F, 0.3F)
            .texOffs(SKIN[1][0], SKIN[1][1]).addBox(-3.7F, -5.2F, -9.7F, 1.4F, 1.4F, 0.3F), PartPose.ZERO);
    }

    /**
     * A stubby leg hanging from its hip, a narrower foot under it and two pale claws, pointing ahead or, leaning back,
     * behind.
     */
    private static CubeListBuilder leg(boolean back) {
        float claws = back ? 2.5F : -4.5F;
        return CubeListBuilder.create()
            .texOffs(SKIN[4][0], SKIN[4][1]).addBox(-3, 0, -3, 6, 6, 6)
            .texOffs(SKIN[2][0], SKIN[2][1]).addBox(-2.5F, 6, -2.5F, 5, 4, 5)
            .texOffs(0, CLAW_V).addBox(-1.75F, 9, claws, 1, 1, 2)
            .texOffs(0, CLAW_V).addBox(0.75F, 9, claws, 1, 1, 2);
    }

    @Override
    public ModelPart root() {
        return root;
    }

    @Override
    public void prepareMobModel(Tardigrade creature, float limbSwing, float limbSwingAmount, float partialTick) {
        float curling = creature.curl(partialTick);
        curl = curling * curling * (3 - 2 * curling);
        float settling = creature.sleep(partialTick);
        sleep = settling * settling * (3 - 2 * settling) * (1 - curl);
        munch = creature.munchShown(partialTick);
        charge = creature.charge(partialTick);
        wriggle = creature.wiggleShown(partialTick);
    }

    @Override
    public void setupAnim(Tardigrade creature, float limbSwing, float limbSwingAmount, float ageInTicks, float netHeadYaw, float headPitch) {
        root.getAllParts().forEach(TardigradeModel::reset);
        float open = 1 - curl;
        for (int i = 0; i < segments.length; i++) {
            ModelPart segment = segments[i];
            float sway = SWAY * limbSwingAmount * Mth.sin(limbSwing * STRIDE_RATE / 2 + i * 0.9F) + WRIGGLE * wriggle * Mth.sin(ageInTicks * 0.9F + i * 1.3F);
            segment.yRot = sway * open;
            segment.z += TUN_ALONG[i] * curl;
            segment.y += TUN_DROP * curl;
            segment.xScale = 1 + TUN_FATTER * curl;
            segment.zScale = segment.xScale;
            segment.yScale = 1 - TUN_FLATTER * curl + 0.01F * Mth.sin(ageInTicks * 0.08F) + SLEEP_BREATH * sleep * Mth.sin(ageInTicks * SLEEP_BREATH_RATE);
            segment.y += SLEEP_DROP * sleep;
        }
        for (int i = 0; i < legs.length; i++) {
            ModelPart leg = legs[i];
            float phase = limbSwing * STRIDE_RATE + (i / 2) * Mth.HALF_PI + (i % 2) * Mth.PI;
            leg.xRot += STRIDE * limbSwingAmount * Mth.sin(phase);
            leg.y -= Math.max(0, Mth.cos(phase)) * limbSwingAmount + TUN_DROP * 0.5F * curl;
            leg.yScale = open * (1 - SLEEP_LEG_FOLD * sleep);
            leg.y += SLEEP_DROP * sleep;
            leg.visible = curl < 0.98F;
        }
        float chew = munch > 0 ? Math.abs(Mth.sin(ageInTicks * 1.1F)) : 0;
        float awake = open * (1 - sleep);
        head.yRot = netHeadYaw * Mth.DEG_TO_RAD * awake;
        head.xRot = (headPitch * Mth.DEG_TO_RAD + BOB * munch * Mth.sin(ageInTicks * 1.1F)) * awake + SLEEP_HEAD_TIP * sleep;
        head.y += (SLEEP_DROP + SLEEP_HEAD_DROP) * sleep;
        head.z += TUN_HEAD_IN * curl + TUN_ALONG[0] * curl;
        head.y += TUN_DROP * curl;
        head.xScale = 1 - 0.4F * curl;
        head.yScale = head.xScale;
        head.zScale = head.xScale;
        head.visible = curl < 0.98F;
        lip.xScale = 1 + CHEW * munch * chew;
        lip.yScale = lip.xScale;
        lids.visible = sleep > 0.5F;
    }

    /** A part as it was built, its size too. */
    private static void reset(ModelPart part) {
        part.resetPose();
        part.xScale = 1;
        part.yScale = 1;
        part.zScale = 1;
        part.visible = true;
    }

    /** Drawn a shade drier as it curls up, and glowing spore blue as it charges up to jump. */
    @Override
    public void renderToBuffer(PoseStack poseStack, VertexConsumer buffer, int packedLight, int packedOverlay, int color) {
        int shade = FastColor.ARGB32.lerp(curl, 0xFFFFFFFF, TUN_SHADE);
        float flicker = charge * (1 - GLOW_FLICKER + GLOW_FLICKER * (float) Math.random());
        shade = FastColor.ARGB32.lerp(flicker, shade, SPORE_GLOW);
        int light = charge > GLOWS_FROM ? LightTexture.FULL_BRIGHT : packedLight;
        root.render(poseStack, buffer, light, packedOverlay, FastColor.ARGB32.multiply(color, shade));
    }
}
